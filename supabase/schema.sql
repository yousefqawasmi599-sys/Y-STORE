create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  name_ar text,
  description text not null default '',
  cat text not null references public.categories (slug) on update cascade,
  price numeric(10, 2) not null check (price > 0),
  img text not null default '/images/product-1.jpg',
  colors jsonb not null default '[]'::jsonb check (jsonb_typeof(colors) = 'array'),
  stock integer not null default 0 check (stock >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  user_id uuid references auth.users (id) on delete set null,
  customer jsonb not null,
  status text not null default 'New' check (status in ('New', 'Processing', 'Shipped', 'Completed', 'Cancelled')),
  shipping text not null check (shipping in ('std', 'exp')),
  payment text not null check (payment = 'cod'),
  subtotal numeric(10, 2) not null check (subtotal >= 0),
  delivery numeric(10, 2) not null check (delivery >= 0),
  total numeric(10, 2) not null check (total >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  product_id bigint references public.products (id) on delete set null,
  product_name text not null,
  size text not null check (size in ('S', 'M', 'L', 'XL', 'XXL', 'ONE SIZE')),
  color text not null,
  qty integer not null check (qty > 0),
  unit_price numeric(10, 2) not null check (unit_price > 0)
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

